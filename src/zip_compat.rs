//! Kujo filename compatibility across the ZIP 9 Rust API migration.
use std::io::Read;

pub(crate) fn entry_name<R: Read>(entry: &zip::read::ZipFile<'_, R>) -> String {
    // ZIP 7 followed the language-encoding flag; ZIP 9 guesses UTF-8 first.
    // Validated Info-ZIP UnicodePath fields also set this flag in ZIP 9.
    if entry.flags().as_u16() & (1 << 11) != 0 {
        String::from_utf8_lossy(entry.name_raw()).into_owned()
    } else {
        entry
            .name_raw()
            .iter()
            .map(
                |&byte| {
                    if byte < 128 {
                        char::from(byte)
                    } else {
                        CP437_HIGH[usize::from(byte - 128)]
                    }
                },
            )
            .collect()
    }
}

